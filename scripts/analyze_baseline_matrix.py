"""Aggregate matched baseline-matrix CSVs and compute paired differences vs MFI.

The confidence interval is a normal-approximation interval and is descriptive;
use more repetitions and an appropriate paired statistical test for final claims.
"""
from __future__ import annotations

import argparse
import csv
import math
import statistics
from collections import defaultdict
from pathlib import Path

# Permit running directly from a checkout.
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

METRICS = (
    "acceptance_rate", "mean_decision_time_ns",
    "mean_time_weighted_fragmentation_score",
    "mean_arrival_snapshot_compute_utilization",
    "mean_arrival_snapshot_memory_utilization",
    "mean_arrival_snapshot_active_gpus",
)


def read_rows(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def mean_sd(values: list[float]) -> tuple[float, float]:
    if not values:
        return 0.0, 0.0
    return statistics.mean(values), statistics.stdev(values) if len(values) > 1 else 0.0


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path, help="CSV generated by run_baseline_matrix.py")
    parser.add_argument("--out-prefix", type=Path, default=Path("results/baseline_analysis"))
    args = parser.parse_args()
    rows = read_rows(args.input)
    if not rows:
        raise SystemExit("Input CSV has no rows")

    by_scenario_policy: dict[tuple[str, str], list[dict]] = defaultdict(list)
    by_scenario_seed_policy = {(r["scenario"], r["seed"], r["policy"]): r for r in rows}
    for row in rows:
        by_scenario_policy[(row["scenario"], row["policy"])].append(row)

    summary = []
    for (scenario, policy), group in sorted(by_scenario_policy.items()):
        out = {"scenario": scenario, "policy": policy, "n_runs": len(group)}
        for metric in METRICS:
            m, sd = mean_sd([float(r[metric]) for r in group])
            out[f"{metric}_mean"] = m
            out[f"{metric}_sd"] = sd
        summary.append(out)

    paired = []
    scenarios = sorted({r["scenario"] for r in rows})
    policies = sorted({r["policy"] for r in rows if r["policy"] != "mfi"})
    for scenario in scenarios:
        seeds = sorted({r["seed"] for r in rows if r["scenario"] == scenario}, key=int)
        for policy in policies:
            deltas = []
            for seed in seeds:
                key_base = (scenario, seed, "mfi")
                key_policy = (scenario, seed, policy)
                if key_base not in by_scenario_seed_policy or key_policy not in by_scenario_seed_policy:
                    continue
                deltas.append(
                    float(by_scenario_seed_policy[key_policy]["acceptance_rate"])
                    - float(by_scenario_seed_policy[key_base]["acceptance_rate"])
                )
            if not deltas:
                continue
            m, sd = mean_sd(deltas)
            half = 1.96 * sd / math.sqrt(len(deltas)) if len(deltas) > 1 else 0.0
            paired.append({
                "scenario": scenario, "policy": policy, "n_paired_seeds": len(deltas),
                "acceptance_delta_vs_mfi_mean": m,
                "acceptance_delta_vs_mfi_sd": sd,
                "normal_approx_95ci_low": m - half,
                "normal_approx_95ci_high": m + half,
                "interval_note": "normal approximation; exploratory only, especially for small n",
            })

    args.out_prefix.parent.mkdir(parents=True, exist_ok=True)
    summary_path = args.out_prefix.with_name(args.out_prefix.name + "_summary.csv")
    paired_path = args.out_prefix.with_name(args.out_prefix.name + "_paired_vs_mfi.csv")
    for path, data in ((summary_path, summary), (paired_path, paired)):
        with path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(data[0]) if data else [])
            if data:
                writer.writeheader(); writer.writerows(data)
    print(f"Wrote aggregate summary: {summary_path.resolve()}")
    print(f"Wrote paired acceptance differences: {paired_path.resolve()}")
    print("Interpret intervals cautiously; use many independent seeds for final inference.")


if __name__ == "__main__":
    main()
